"""Regenerate report tables and publication figures from the retained evidence.

Run with Python and matplotlib from the repository root. Does not run inference
or overwrite research results. Figure panels deliberately separate protocols.
"""
from pathlib import Path
import hashlib
import json

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RESULTS = ROOT/'evaluation/results'
TABLES = HERE/'tables'
FIGURES = HERE/'images'
TABLES.mkdir(exist_ok=True)


def read(name):
    return json.loads((RESULTS/(name+'.json')).read_text(encoding='utf-8-sig'))


def table(name, headings, rows, columns=None):
    columns = columns or ('l'+'r'*(len(headings)-1))
    lines = ['% Generated by generate_evidence.py; edit the source data or script.',
             r'\begin{tabular}{@{}'+columns+r'@{}}',r'\toprule',
             ' & '.join(r'\textbf{'+s+'}' for s in headings)+r' \\ \midrule']
    lines += [' & '.join(str(s) for s in row)+r' \\' for row in rows]
    lines += [r'\bottomrule',r'\end{tabular}']
    (TABLES/(name+'.tex')).write_text('\n'.join(lines)+'\n',encoding='utf-8')


def clean(d):
    if isinstance(d,dict):
        return {k:clean(v) for k,v in d.items() if k not in {'records','queries','results'}}
    if isinstance(d,list):return [clean(v) for v in d]
    return d


def main():
    rows=[]
    for category in sorted((ROOT/'datasets/clothing_small/train').iterdir()):
        if not category.is_dir():continue
        counts=[sum(p.suffix.lower() in {'.jpg','.jpeg','.png','.webp','.bmp'} for p in
                    (ROOT/'datasets/clothing_small'/split/category.name).rglob('*') if p.is_file())
                for split in ['train','validation','test']]
        label=category.name.replace('outwear','Outerwear').replace('longsleeve','Long sleeve').replace('t-shirt','T-shirt').title()
        rows.append([label,*counts])
    rows.append(['Total',3068,341,372])
    table('dataset',['Category','Gallery','Validation','Test'],rows)
    baseline=[]
    for key,label in [('resnet50','ResNet50'),('efficientnet_b3','EfficientNet-B3'),('clip','CLIP'),('dinov2','DINOv2'),('siglip2','SigLIP2')]:
        d=read(key)
        baseline.append([label,d['embedding_dimension'],f"{100*d['precision_at_1']:.2f}",f"{100*d['precision_at_5']:.2f}",f"{d['map_at_10']:.4f}",f"{d['mrr_at_10']:.4f}"])
    table('encoders',['Encoder','$d$','P@1 (\\%)','P@5 (\\%)','mAP@10','MRR@10'],baseline)
    d=read('FINAL_TEST_RESULTS')
    table('historical_test',['Input','P@1 (\\%)','P@5 (\\%)','mAP@10','MRR@10'],[
        [label,f"{100*d[key]['precision_at_1']:.2f}",f"{100*d[key]['precision_at_5']:.2f}",f"{d[key]['map_at_10']:.4f}",f"{d[key]['mrr_at_10']:.4f}"]
        for key,label in [('clean_test','Clean test'),('multi_product_full_image','Composite: full'),('multi_product_sam2','Composite: SAM2')]])
    routing=read('category_routing_comparison')['suites']
    table('routing',['Split','$n$','All (\\%)','Auto (\\%)','Gain (pp)','Better / worse'],[
        [split.title(),v['query_count'],f"{100*v['unrestricted_top1']:.2f}",f"{100*v['auto_top1']:.2f}",f"{100*v['auto_vs_unrestricted']['delta_top1']:.2f}",f"{v['auto_vs_unrestricted']['improved_queries']} / {v['auto_vs_unrestricted']['worsened_queries']}"]
        for split,v in routing.items()])
    crop=read('safe_crop_catalog_ab')['suites']
    table('cropping',['Query set','$n$','Original (\\%)','Crop (\\%)','Hybrid (\\%)'],[
        [label,v['query_count'],*[f"{100*v[m]['precision_at_1']:.2f}" for m in ['original','safe_crop','hybrid']]]
        for key,label in [('clean_test','Clean test'),('multi_product_full','Composite: full'),('multi_product_selected','Composite: selected')]
        for v in [crop[key]]])
    # A compact, inspectable numeric snapshot, without individual user data.
    snapshot={n:clean(read(n)) for n in ['FINAL_TEST_RESULTS','safe_crop_catalog_ab','category_routing_comparison','reviewed_identity_pilot','reviewed_reverse_sam_pilot']}
    snapshot['source_hashes']={str(p.relative_to(ROOT)).replace('\\','/'):hashlib.sha256(p.read_bytes()).hexdigest() for p in RESULTS.glob('*.json')}
    (HERE/'notes/evidence_snapshot.json').write_text(json.dumps(snapshot,indent=2)+'\n',encoding='utf-8')
    plt.rcParams.update({'font.family':'DejaVu Sans','font.size':10,'axes.spines.top':False,'axes.spines.right':False,'pdf.fonttype':42})
    fig,ax=plt.subplots(figsize=(6.4,3.6),layout='constrained')
    values=[46,75]
    bars=ax.bar(['Full image','SAM2 selection'],values,width=.5,color=['#9caab8','#00588f'])
    ax.bar_label(bars,labels=['46/100','75/100'],padding=4)
    ax.set_ylim(0,100);ax.set_ylabel('Category-correct first result (%)')
    ax.set_title('Historical synthetic test: same 100 composite queries',fontsize=11)
    ax.grid(axis='y',alpha=.17);ax.set_axisbelow(True)
    fig.savefig(FIGURES/'historical_sam2.pdf');plt.close(fig)
    fig,ax=plt.subplots(figsize=(6.4,3.7),layout='constrained')
    x=[0,1];width=.30
    a=[routing[k]['unrestricted_top1']*100 for k in ['validation','test']]
    b=[routing[k]['auto_top1']*100 for k in ['validation','test']]
    bars1=ax.bar([p-width/2 for p in x],a,width,label='All categories',color='#9caab8')
    bars2=ax.bar([p+width/2 for p in x],b,width,label='Automatic category',color='#00588f')
    for bars in [bars1,bars2]:ax.bar_label(bars,fmt='%.2f',padding=3,fontsize=9)
    ax.set_xticks(x,['Validation (341)','Test (372)']);ax.set_ylim(0,108)
    ax.set_yticks([0,20,40,60,80,100]);ax.set_ylabel('Category-correct first result (%)')
    ax.set_title('Application-aligned clean-query comparison',fontsize=11)
    ax.legend(loc='upper center',bbox_to_anchor=(0.5,-0.16),ncol=2,frameon=False)
    ax.grid(axis='y',alpha=.17);ax.set_axisbelow(True)
    fig.savefig(FIGURES/'category_routing.pdf');plt.close(fig)
    print('Generated five evidence tables, two vector figures, and a source-hashed numeric snapshot.')


if __name__=='__main__':main()
